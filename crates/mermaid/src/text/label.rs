    #[test]
    fn layout_label_matches_pele() {
        let resolver: &dyn Fn(&str) -> Option<String> = &icons;
        for &(raw, markdown, size, max, base, with_icons, expected, svg) in CASES {
            let icons = with_icons.then_some(resolver);
            let label = layout_label(raw, markdown, size, max, base, icons);
            assert_eq!(
                repr(&label),
                expected,
                "{raw:?} markdown={markdown} max={max}"
            );
            assert_eq!(
                label_svg(&label, 50.5, -20.25, " class=\"l\"", icons),
                svg,
                "{raw:?}"
            );
        }
    }
